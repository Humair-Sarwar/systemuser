export const findDialCountry = (dialCode, iso) => {
  if (iso) {
    const byIso = ALL_COUNTRY_DIAL_CODES.find((c) => c.iso === iso.toLowerCase());
    if (byIso) return byIso;
  }
  if (dialCode) {
    const normalized = String(dialCode).startsWith("+") ? String(dialCode) : `+${dialCode}`;
    const byDial = ALL_COUNTRY_DIAL_CODES.find((c) => c.dialCode === normalized);
    if (byDial) return byDial;
  }
  return ALL_COUNTRY_DIAL_CODES[0];
};

/**
 * Renders a crisp vector SVG country flag via `flag-icons` for any ISO 3166-1 alpha-2 code or dial code.
 */
export const CountryFlag = React.memo(function CountryFlag({ iso, code, width = 22, height = 15 }) {
  const resolvedIso = React.useMemo(() => {
    if (iso) return String(iso).toLowerCase();
    return findDialCountry(code)?.iso || "gb";
  }, [iso, code]);

  return React.createElement("span", {
    className: `fi fi-${resolvedIso}`,
    "aria-hidden": "true",
    style: {
      width,
      height,
      borderRadius: 3,
      display: "inline-block",
      flexShrink: 0,
      backgroundSize: "cover",
      boxShadow: "0 0 1px rgba(15, 23, 42, 0.35)",
    },
  });
});
